name = "debananda"
print(len(name))  # This will print the length of the string 'debananda', which is 9

print(name.endswith("da"))  # This checks if the string ends with 'da' and returns True

print(name.startswith("de"))  # This checks if the string starts with 'de' and returns True
# These are case sensitive

print(name.capitalize())# This will capitalize the first letter of the string and make the rest lowercase, output: 'Debananda'